// BuildPrompt собирает адаптивный контекст диалога с учётом базы знаний и истории.
func BuildPrompt(persona AgentPersona, article KnowledgeArticle, userMessage string, history []string) string {
	historyBlock := ""
	if len(history) > 0 {
		historyBlock = "Предыдущий контекст беседы:\n"
		for _, h := range history {
			historyBlock += "- " + h + "\n"
		}
	}

	return fmt.Sprintf(`%s

%s
Материал из бортовой базы знаний станции:
- Источник: %s
- Фрагмент: "%s"

Вопрос игрока-исследователя: "%s"

Сформулируй свой ответ в рамках роли. Ссылайся на факты из источника, но говори от первого лица. Если игрок ищет компромисс по энергии — поддержи эту мысль!`,
		persona.SystemPrompt,
		historyBlock,
		article.Title,
		article.FullQuote,
		userMessage,
	)
}
