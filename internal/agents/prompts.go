// BuildPrompt собирает адаптивный контекст диалога с учётом базы знаний и истории.
func BuildPrompt(persona AgentPersona, article KnowledgeArticle, userMessage string, history []string) string {
	return BuildAdaptivePrompt(persona, article, userMessage, history, nil, nil)
}

// BuildAdaptivePrompt собирает полный персонализированный промпт с адаптацией под ошибки игрока и чипы подсказок.
func BuildAdaptivePrompt(persona AgentPersona, article KnowledgeArticle, userMessage string, history []string, mistakes []string, chips []string) string {
	var sb strings.Builder

	sb.WriteString(persona.SystemPrompt)
	sb.WriteString("\n\n")

	if len(mistakes) > 0 {
		sb.WriteString("ИСТОРИЯ ОШИБОК ИГРОКА (ОБЯЗАТЕЛЬНО УЧЕСТЬ В ОТВЕТЕ):\n")
		sb.WriteString("Игрок ранее допустил следующие неверные гипотезы:\n")
		for _, m := range mistakes {
			sb.WriteString(fmt.Sprintf("- %s\n", m))
		}
		sb.WriteString("ПРАВИЛО: Запрещено читать сухую вводную лекцию. Начни ответ с доброжелательной ссылки на эту ошибку и покажи, в чём именно парадокс!\n\n")
	}

	if len(chips) > 0 {
		sb.WriteString("РЕЖИМ ПОДАЧИ МАТЕРИАЛА:\n")
		for _, c := range chips {
			switch c {
			case "explain_simpler", "simpler":
				sb.WriteString("- ОБЪЯСНИ ПРОЩЕ: Используй максимально доступные слова без сложных математических формул.\n")
			case "give_analogy", "analogy":
				sb.WriteString("- БЫТОВОЙ ПРИМЕР: Приведи наглядный бытовой образ (поезд, зеркальный вагончик, мячик, луч фонаря).\n")
			}
		}
		sb.WriteString("\n")
	}

	if len(history) > 0 {
		sb.WriteString("Предыдущий контекст беседы:\n")
		for _, h := range history {
			sb.WriteString("- " + h + "\n")
		}
		sb.WriteString("\n")
	}

	sb.WriteString(fmt.Sprintf(`Материал из бортовой базы знаний / первоисточника:
- Источник: %s
- Фрагмент: "%s"

Вопрос игрока-исследователя: "%s"

Сформулируй свой ответ в рамках роли. Ссылайся на факты из источника, но говори от первого лица.`,
		article.Title,
		article.FullQuote,
		userMessage,
	))

	return sb.String()
}
