// FindKnowledge выполняет локальный поиск по ключевым словам и релевантности.
func FindKnowledge(agentID, query string) (KnowledgeArticle, bool) {
	q := strings.ToLower(query)
	var bestArticle KnowledgeArticle
	bestScore := -1

	for _, art := range StationKnowledgeBase {
		// Фильтр по роли агента
		if agentID != "captain" && agentID != "astra" && art.AgentID != agentID && !containsKeywords(q, art.Keywords) {
			continue
		}

		score := 0
		for _, kw := range art.Keywords {
			if strings.Contains(q, kw) {
				score += 3
			}
		}

		// Бонус за соответствие роли
		if art.AgentID == agentID {
			score += 10
		}

		if score > bestScore {
			bestScore = score
			bestArticle = art
		}
	}

	if bestScore > 0 {
		return bestArticle, true
	}

	// Дефолтная статья для агента, если ключевые слова не совпали
	for _, art := range StationKnowledgeBase {
		if art.AgentID == agentID {
			return art, true
		}
	}

	return StationKnowledgeBase[0], true
}

func containsKeywords(q string, kws []string) bool {
	for _, kw := range kws {
		if strings.Contains(q, kw) {
			return true
		}
	}
	return false
}
